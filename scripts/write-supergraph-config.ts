// Writes router/supergraph.yaml containing only the subgraphs for the given Level.
// Run directly: LEVEL=2 node scripts/write-supergraph-config.ts

import { writeFileSync } from 'node:fs';
import { levelFromEnv, subgraphsUpToLevel } from './subgraphs.ts';

const FEDERATION_VERSION = '=2.15.4';
const CONFIG_PATH = new URL('../router/supergraph.yaml', import.meta.url);

export function writeSupergraphConfig(level: number): void {
  const lines = [
    `# GENERATED by scripts/write-supergraph-config.ts for LEVEL=${level}. Don't edit by hand.`,
    `# Schema paths are relative to this file.`,
    `federation_version: "${FEDERATION_VERSION}"`,
    `subgraphs:`,
  ];
  for (const subgraph of subgraphsUpToLevel(level)) {
    lines.push(
      `  ${subgraph.name}:`,
      `    routing_url: http://localhost:${subgraph.port}`,
      `    schema:`,
      `      file: ../subgraphs/${subgraph.name}/schema.graphql`,
    );
  }
  writeFileSync(CONFIG_PATH, lines.join('\n') + '\n');
}

if (import.meta.main) {
  writeSupergraphConfig(levelFromEnv());
}
